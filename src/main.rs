/// Simple Rust CLI harness for AI code generation and autonomous agentic workflow.
#[derive(Parser)]
#[command(name = "ctrl-cli")]
#[command(author = "Generated by Antigravity")]
#[command(version = "0.2.0")]
#[command(about = "Ultra-lightweight AI Coding Agent CLI with tool execution", long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Option<Commands>,
}

#[derive(Subcommand)]
enum Commands {
    /// Generate code or complete an agentic task from a prompt.
    Generate {
        /// Model name override (e.g. glm-5.3-flash, deepseek-chat, gpt-4o-mini).
        #[arg(short, long)]
        model: Option<String>,

        /// Skill to activate for generation (e.g. rust-expert, code-reviewer, web-frontend).
        #[arg(short, long)]
        skill: Option<String>,

        /// Show token usage and context window metrics.
        #[arg(short = 't', long)]
        tokens: bool,

        /// Save generated code directly to file instead of printing to terminal.
        #[arg(short, long)]
        output: Option<String>,

        /// Prompt to send to the AI code generation provider.
        #[arg(num_args = 1.., required = true)]
        prompt: Vec<String>,
    },
}

