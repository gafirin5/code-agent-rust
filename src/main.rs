#[derive(Clone, Debug, Default)]
struct SessionTokenTracker {
    total_prompt_tokens: u64,
    total_completion_tokens: u64,
    total_tokens: u64,
    query_count: u64,
    last_usage: Option<Usage>,
    last_model: Option<String>,
    last_content: Option<String>,
}

impl SessionTokenTracker {
    fn record(&mut self, usage: Option<&Usage>, model: &str, content: &str) {
        self.query_count += 1;
        self.last_model = Some(model.to_string());
        self.last_content = Some(content.to_string());
        if let Some(u) = usage {
            let p = u.prompt_tokens.unwrap_or(0);
            let c = u.completion_tokens.unwrap_or(0);
            let t = u.total_tokens.unwrap_or(p + c);
            self.total_prompt_tokens += p;
            self.total_completion_tokens += c;
            self.total_tokens += t;
            self.last_usage = Some(u.clone());
        }
    }
}

fn extract_code_block(text: &str) -> String {
    if let Some(start_idx) = text.find("```") {
        let after_fence = &text[start_idx + 3..];
        let code_start = after_fence.find('\n').map(|n| n + 1).unwrap_or(0);
        let code_body = &after_fence[code_start..];
        if let Some(end_idx) = code_body.find("```") {
            return code_body[..end_idx].to_string();
        }
    }
    text.to_string()
}

fn detect_filename(text: &str) -> Option<String> {
    let extensions = [
        ".html", ".htm", ".rs", ".py", ".ts", ".js", ".css", ".json",
        ".toml", ".yaml", ".yml", ".md", ".sh", ".sql", ".zig", ".go", ".c", ".cpp",
    ];

    for line in text.lines() {
        let trimmed = line.trim();
        let mut rest = trimmed;
        while let Some(start) = rest.find('`') {
            let after = &rest[start + 1..];
            if let Some(end) = after.find('`') {
                let candidate = after[..end].trim();
                if !candidate.contains(' ') && candidate.len() <= 50 && candidate.len() >= 3 {
                    if extensions.iter().any(|ext| candidate.ends_with(ext)) {
                        return Some(candidate.to_string());
                    }
                }
                rest = &after[end + 1..];
            } else {
                break;
            }
        }
        let mut rest_bold = trimmed;
        while let Some(start) = rest_bold.find("**") {
            let after = &rest_bold[start + 2..];
            if let Some(end) = after.find("**") {
                let candidate = after[..end].trim();
                if !candidate.contains(' ') && candidate.len() <= 50 && candidate.len() >= 3 {
                    if extensions.iter().any(|ext| candidate.ends_with(ext)) {
                        return Some(candidate.to_string());
                    }
                }
                rest_bold = &after[end + 2..];
            } else {
                break;
            }
        }
    }
    None
}

fn save_code_to_file(path_str: &str, content: &str) -> Result<String> {
    let path = std::path::Path::new(path_str);
    if let Some(parent) = path.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)?;
        }
    }
    let code = extract_code_block(content);
    std::fs::write(path, code.as_bytes())?;
    let line_count = code.lines().count();
    let bytes = code.len();
    Ok(format!("{} ({} baris, {} byte)", path_str, line_count, bytes))
}

fn auto_save_if_code_generated(prompt: &str, final_content: &str, tools_executed: usize) -> Option<String> {
    if tools_executed > 0 {
        return None;
    }
    let code = extract_code_block(final_content);
    if code.lines().count() >= 3 && code != final_content {
        let suggested = detect_filename(final_content)
            .or_else(|| detect_filename(prompt))
            .or_else(|| {
                let lower_p = prompt.to_lowercase();
                if lower_p.contains("html") || lower_p.contains("web") || code.contains("<!DOCTYPE") || code.contains("<html") {
                    Some("index.html".to_string())
                } else if lower_p.contains("python") || code.contains("def ") || code.contains("import sys") {
                    Some("main.py".to_string())
                } else if lower_p.contains("rust") || code.contains("fn main") {
                    Some("main.rs".to_string())
                } else {
                    None
                }
            });

        if let Some(fname) = suggested {
            if let Ok(summary) = save_code_to_file(&fname, &code) {
                let _ = MemoryManager::save_long_term_memory("append", &format!("Created file '{}'", fname));
                return Some(format!("💾 [Auto-Writer Memory] Mendeteksi kode untuk '{}'. File otomatis disimpan: {}\n", fname, summary));
            }
        }
    }
    None
}

fn format_number(n: u64) -> String {
    let s = n.to_string();
    let mut result = String::new();
    let len = s.len();
    for (i, ch) in s.chars().enumerate() {
        if i > 0 && (len - i) % 3 == 0 {
            result.push(',');
        }
        result.push(ch);
    }
    result
}

fn format_token_badge(usage: Option<&Usage>, model: &str) -> String {
    let ctx_info = get_model_context_info(model);
    if let Some(u) = usage {
        let p = u.prompt_tokens.unwrap_or(0);
        let c = u.completion_tokens.unwrap_or(0);
        let t = u.total_tokens.unwrap_or(p + c);
        let pct = if ctx_info.context_window > 0 {
            (p as f64 / ctx_info.context_window as f64) * 100.0
        } else {
            0.0
        };
        let ctx_label = if ctx_info.context_window >= 1_000_000 {
            format!("{}M", ctx_info.context_window / 1_000_000)
        } else if ctx_info.context_window >= 1_000 {
            format!("{}k", ctx_info.context_window / 1_000)
        } else {
            format!("{}", ctx_info.context_window)
        };
        format!(
            "📊 [Tokens: {} in + {} out = {} total | Context: {:.2}% of {}]",
            format_number(p),
            format_number(c),
            format_number(t),
            pct,
            ctx_label
        )
    } else {
        format!(
            "📊 [Model: {} | Context Window: {}]",
            model, ctx_info.note
        )
    }
}

