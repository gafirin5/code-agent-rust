#[derive(Clone, Default)]
struct SlashCompleter;

impl Autocomplete for SlashCompleter {
    fn get_suggestions(&mut self, input: &str) -> Result<Vec<String>, CustomUserError> {
        let mut suggestions = Vec::new();
        if input.starts_with("/model ") {
            let prefix = &input["/model ".len()..];
            let models = [
                "glm-5.3-flash",
                "glm-4-plus",
                "deepseek-chat",
                "deepseek-reasoner",
                "llama-3.3-70b-versatile",
                "qwen-2.5-coder-32b",
                "gpt-4o-mini",
                "gpt-4o",
                "anthropic/claude-3.5-sonnet",
            ];
            for m in models {
                if m.to_lowercase().starts_with(&prefix.to_lowercase()) {
                    suggestions.push(format!("/model {}", m));
                }
            }
        } else if input.starts_with("/skill ") {
            let prefix = &input["/skill ".len()..];
            let mut skill_ids: Vec<&str> = get_available_skills().iter().map(|s| s.id).collect();
            skill_ids.push("reset");
            for id in skill_ids {
                if id.to_lowercase().starts_with(&prefix.to_lowercase()) {
                    suggestions.push(format!("/skill {}", id));
                }
            }
        } else if input.starts_with('/') {
            let commands = [
                "/tools",
                "/permissions",
                "/memory",
                "/tokens",
                "/tokens toggle",
                "/usage",
                "/context",
                "/reset",
                "/save",
                "/write",
                "/model",
                "/skill",
                "/dev",
                "/profile",
                "/info",
                "/clear",
                "/help",
                "/exit",
            ];
            for cmd in commands {
                if cmd.starts_with(input) {
                    suggestions.push(cmd.to_string());
                }
            }
        }
        Ok(suggestions)
    }

    fn get_completion(
        &mut self,
        _input: &str,
        highlighted_suggestion: Option<String>,
    ) -> Result<Replacement, CustomUserError> {
        Ok(Replacement::Some(highlighted_suggestion.unwrap_or_default()))
    }
}

fn main() -> Result<()> {
    load_env_file();
    let mut profile = load_user_profile();
    let cli = Cli::parse();

    match cli.command {
        Some(Commands::Generate { model, skill, tokens, output, prompt }) => {
            let full_prompt = prompt.join(" ");
            let skill_obj = skill.and_then(|s_name| {
                get_available_skills()
                    .into_iter()
                    .find(|s| s.id.eq_ignore_ascii_case(&s_name))
            });
            handle_generate(&full_prompt, model.as_deref(), skill_obj.as_ref(), &profile, tokens, output.as_deref())?;
        }
        None => {
            start_repl(&mut profile)?;
        }
    }
    Ok(())
}

fn load_env_file() {
    let mut candidates = Vec::new();
    if let Ok(curr) = std::env::current_dir() {
        candidates.push(curr.join(".env"));
    }
    candidates.push(PathBuf::from(r"C:\Users\Administrator\code-agent-rust\ctrl-cli\.env"));

    for candidate in candidates {
        if candidate.exists() {
            if let Ok(content) = std::fs::read_to_string(&candidate) {
                for line in content.lines() {
                    let trimmed = line.trim();
                    if trimmed.is_empty() || trimmed.starts_with('#') {
                        continue;
                    }
                    if let Some((k, v)) = trimmed.split_once('=') {
                        let key = k.trim();
                        let mut val = v.trim();
                        if (val.starts_with('"') && val.ends_with('"'))
                            || (val.starts_with('\'') && val.ends_with('\''))
                        {
                            if val.len() >= 2 {
                                val = &val[1..val.len() - 1];
                            }
                        }
                        if std::env::var(key).is_err() {
                            std::env::set_var(key, val);
                        }
                    }
                }
            }
            break;
        }
    }
}

